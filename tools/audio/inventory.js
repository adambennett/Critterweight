'use strict';
// Hash-checked inventories for generated and imported audio. No audio is rendered or changed.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.resolve(__dirname, '../..');
const audio = path.join(root, 'game/assets/audio');
const manifest = JSON.parse(fs.readFileSync(path.join(audio, 'manifest.json'), 'utf8'));
const bank = JSON.parse(fs.readFileSync(path.join(audio, 'bank.json'), 'utf8'));
const refs = new Map();
function walk(value, route) {
  if (typeof value === 'string' && value.startsWith('res://assets/audio/')) {
    const rel = value.slice('res://assets/audio/'.length);
    if (!refs.has(rel)) refs.set(rel, []);
    refs.get(rel).push(route);
  } else if (Array.isArray(value)) value.forEach((v, i) => walk(v, route + '[' + i + ']'));
  else if (value && typeof value === 'object') Object.entries(value).forEach(([k, v]) => walk(v, route ? route + '.' + k : k));
}
walk(bank, 'bank');
const files = Object.entries(manifest.files).sort(([a], [b]) => a.localeCompare(b)).map(([rel, info]) => {
  const actual = crypto.createHash('sha256').update(fs.readFileSync(path.join(audio, rel))).digest('hex');
  if (actual !== info.sha256) throw new Error('Manifest mismatch: ' + rel);
  return { file: 'game/assets/audio/' + rel, group: rel.split('/')[0], seconds: info.seconds,
    sample_rate: info.sr, channels: info.channels, bytes: info.bytes, sha256: actual,
    bank_references: refs.get(rel) || [], generated_by: 'tools/audio/build.js' };
});
const groups = {};
for (const f of files) groups[f.group] = (groups[f.group] || 0) + 1;
const out = path.join(root, 'docs/audio');
fs.mkdirSync(out, { recursive: true });
const payload = { version: 1, source: 'game/assets/audio/manifest.json', count: files.length,
  total_bytes: files.reduce((sum, f) => sum + f.bytes, 0), groups,
  note: 'All entries are generated by the repository DSP/synthesis pipeline. Imported third-party replacement audio is listed separately.', files };
fs.writeFileSync(path.join(out, 'generated-audio-inventory.json'), JSON.stringify(payload, null, 2) + '\n');
const lines = ['CRITTERWEIGHT GENERATED AUDIO INVENTORY', '', files.length + ' files; ' + (payload.total_bytes / 1048576).toFixed(1) + ' MiB',
  payload.note, '', 'Group counts:', ...Object.entries(groups).map(([g, n]) => '  ' + g + ': ' + n), '',
  'Every file (repository-relative paths; duration, sample rate and bank references):', ''];
for (const f of files) lines.push(f.file, '  ' + f.seconds + 's | ' + f.sample_rate + ' Hz | ' + f.channels + ' channel(s)',
  '  ' + (f.bank_references.join('; ') || 'Referenced indirectly by its voice grain bank'));
fs.writeFileSync(path.join(out, 'generated-audio-inventory.txt'), lines.join('\n') + '\n');

const provenancePath = path.join(audio, 'replacements', 'provenance.json');
const provenance = JSON.parse(fs.readFileSync(provenancePath, 'utf8'));
const replacementRoot = path.join(audio, 'replacements');
const replacementAudio = [];
function walkReplacement(dir) {
  for (const name of fs.readdirSync(dir)) {
    const file = path.join(dir, name);
    if (fs.statSync(file).isDirectory()) walkReplacement(file);
    else if (/\.(ogg|mp3|wav)$/i.test(name)) replacementAudio.push(file);
  }
}
walkReplacement(replacementRoot);
const replacementFiles = [];
const replacementPaths = {};
for (const full of replacementAudio.sort()) {
  const rel = path.relative(replacementRoot, full).replace(/\\/g, '/');
  const prefix = Object.keys(provenance.prefixes).find(k => k.endsWith('/') ? rel.startsWith(k) : rel === k);
  const sourceId = prefix ? provenance.prefixes[prefix] : null;
  if (!sourceId || !provenance.sources[sourceId]) throw new Error('Missing audio provenance: ' + rel);
  const data = fs.readFileSync(full);
  const sha = crypto.createHash('sha256').update(data).digest('hex');
  const bankPath = 'replacements/' + rel;
  const inventoryPath = 'assets/audio/replacements/' + rel;
  const item = { file: inventoryPath, group: rel.split('/')[0], bytes: data.length, sha256: sha,
    source_id: sourceId, creator: provenance.sources[sourceId].creator, title: provenance.sources[sourceId].title,
    license: provenance.sources[sourceId].license, source: provenance.sources[sourceId].source,
    bank_references: refs.get(bankPath) || [] };
  replacementFiles.push(item);
  replacementPaths[inventoryPath] = { sha256: sha, source_id: sourceId, license: item.license,
    bank_references: item.bank_references };
}
const replacementPayload = { version: 1, source: 'game/assets/audio/replacements/provenance.json',
  downloaded: provenance.downloaded, count: replacementFiles.length,
  total_bytes: replacementFiles.reduce((sum, f) => sum + f.bytes, 0),
  note: provenance.notes.join(' '), sources: provenance.sources, paths: replacementPaths, files: replacementFiles };
fs.writeFileSync(path.join(replacementRoot, 'replacement-audio-inventory.json'), JSON.stringify(replacementPayload, null, 2) + '\n');
const replacementLines = ['CRITTERWEIGHT IMPORTED AUDIO REPLACEMENT INVENTORY', '',
  replacementFiles.length + ' files; ' + (replacementPayload.total_bytes / 1048576).toFixed(1) + ' MiB',
  replacementPayload.note, '', 'Every installed file:'];
for (const f of replacementFiles) replacementLines.push('', f.file, '  ' + f.bytes + ' bytes | SHA-256 ' + f.sha256,
  '  ' + f.title + ' — ' + f.creator + ' | ' + f.license, '  Source: ' + f.source,
  '  Bank: ' + (f.bank_references.join('; ') || '(not directly referenced)'));
fs.writeFileSync(path.join(out, 'replacement-audio-inventory.txt'), replacementLines.join('\n') + '\n');
console.log(JSON.stringify({ generated_files: payload.count, generated_groups: groups,
  replacement_files: replacementFiles.length, replacement_bytes: replacementPayload.total_bytes,
  replacement_bank_paths: Object.keys(replacementPaths).filter(p => replacementPaths[p].bank_references.length).length }, null, 2));